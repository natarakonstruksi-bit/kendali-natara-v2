import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const must=(c,m)=>{if(!c)throw new Error(m)};
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'public/index.html'),'utf8');
const sw=fs.readFileSync(path.join(root,'public/sw.js'),'utf8');
const app=fs.readFileSync(path.join(root,'public/app.js'),'utf8');
const man=JSON.parse(fs.readFileSync(path.join(root,'public/manifest.webmanifest'),'utf8'));
must(man.name&&man.short_name&&man.start_url&&man.display==='standalone','Manifest belum lengkap');
for(const ic of man.icons) must(fs.existsSync(path.join(root,'public',ic.src)),`Ikon hilang: ${ic.src}`);
must(man.icons.some(i=>i.sizes==='512x512'&&i.purpose==='any')&&man.icons.some(i=>i.purpose==='maskable'),'Ikon 512 & maskable wajib ada');
must(fs.existsSync(path.join(root,'public/icons/apple-touch-icon.png'))&&fs.existsSync(path.join(root,'public/offline.html')),'apple-touch-icon / offline.html hilang');
for(const mk of ['rel="manifest" href="/manifest.webmanifest"','rel="apple-touch-icon"','apple-mobile-web-app-capable','viewport-fit=cover']) must(html.includes(mk),`index.html belum punya ${mk}`);
const v=(sw.match(/APP_VERSION = '([^']+)'/)||[])[1];
must(v===pkg.version,`Versi sw.js (${v}) harus sama dengan package.json (${pkg.version}) agar cache lama terhapus`);
must(html.includes(`/app.js?v=${pkg.version}`)&&html.includes(`/styles.css?v=${pkg.version}`),'Versi aset index.html tidak sama dengan sw.js');
must(sw.includes('/^\\/api\\//')&&sw.includes("'/offline'")&&!sw.includes("'/offline.html'"),'Service worker: /api harus network-only dan offline memakai /offline');
for(const mk of ["navigator.serviceWorker.register('/sw.js')",'beforeinstallprompt','SKIP_WAITING','naraInstallSheet']) must(app.includes(mk),`Frontend PWA marker hilang: ${mk}`);
console.log('PWA smoke OK — manifest + ikon, service worker berversi, data network-only, offline page, tombol pasang & pembaruan.');
